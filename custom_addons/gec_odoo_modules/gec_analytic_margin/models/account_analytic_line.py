from odoo import models, fields, api


class AccountAnalyticLine(models.Model):
    _inherit = 'account.analytic.line'

    gec_allocation_run_id = fields.Many2one(
        'gec.allocation.run',
        string='Allocation Run',
        ondelete='cascade',
        index='btree_not_null',
        copy=False,
        help="Set on lines generated by a cost allocation run. Deleting the run "
             "deletes these lines.",
    )
    gec_allocation_kind = fields.Selection(
        [('contra', 'Contra'), ('target', 'Target')],
        string='Allocation Line Type',
        copy=False,
        help="Contra: reverses the cost on the source analytic account.\n"
             "Target: carries the allocated share onto the target account.\n"
             "Contra + targets always sum to zero, so allocation never changes "
             "the company total.",
    )
    gec_is_allocation = fields.Boolean(
        string='Is Allocation',
        compute='_compute_gec_is_allocation',
        store=True,
        index=True,
        help="Technical flag for filtering allocation lines out of a "
             "pre-allocation view.",
    )
    gec_allocation_step = fields.Integer(
        string='Allocation Step',
        copy=False,
        index='btree_not_null',
        help="Which step of the cascade produced this line.\n\n"
             "A pool ignores everything allocated at its own step or later — "
             "that is what stops a cost being charged out twice — but it does "
             "take in what earlier steps delivered. IT charged to Development "
             "at step 1 becomes part of Development's pool at step 2.",
    )

    @api.depends('gec_allocation_run_id')
    def _compute_gec_is_allocation(self):
        for line in self:
            line.gec_is_allocation = bool(line.gec_allocation_run_id)

    # Odoo (hr_timesheet) already copies project plan columns to timesheets on create and write;
    # only items posted before the project's tag was set need catching up.
    @api.model
    def _gec_backfill_project_tags(self, plan):
        """Fill one plan's tag on items already posted; returns how many moved.

        Only empty tags are filled: a tag already on an item is more precise than the project's."""
        column = plan._column_name()
        if 'project_id' not in self._fields:
            return 0
        if column not in self._fields or column not in self.env['project.project']._fields:
            return 0
        filled = 0
        for project in self.env['project.project'].search([(column, '!=', False)]):
            lines = self.search([
                ('project_id', '=', project.id), (column, '=', False),
            ])
            if lines:
                lines.write({column: project[column].id})
                filled += len(lines)
        return filled

    @api.model
    def _gec_items_behind_project_tag(self, plan, date_from=None, date_to=None):
        """How many posted items are missing a tag their project could give."""
        column = plan._column_name()
        if 'project_id' not in self._fields:
            return 0
        if column not in self._fields or column not in self.env['project.project']._fields:
            return 0
        domain = [
            ('project_id', '!=', False), (column, '=', False),
            ('project_id.' + column, '!=', False),
        ]
        if date_from:
            domain.append(('date', '>=', date_from))
        if date_to:
            domain.append(('date', '<=', date_to))
        return self.search_count(domain)
