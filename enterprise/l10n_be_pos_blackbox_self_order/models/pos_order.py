from odoo import models, fields


class PosOrder(models.Model):
    _inherit = 'pos.order'

    # TODO-manv: remove in master
    l10n_be_sign_sale_input = fields.Json(
        string="Sign Sale Input",
        help="The full OBOX payload generated by the mobile device for FDM signing.",
    )

    def write(self, vals):
        # Self-orders receipt is sent only once the order is signed (see 'get_order_to_sign')
        orders_to_send = self.browse()
        if vals.get('l10n_be_short_signature'):
            orders_to_send = self.filtered(lambda o: o.source == 'mobile' and o.l10n_be_is_being_signed and not o.l10n_be_short_signature)
        res = super().write(vals)
        for order in orders_to_send:
            order._send_self_order_receipt()
        return res

    def _send_self_order_receipt(self):
        # Only print self-orders receipt once they have been signed
        orders = self.filtered(lambda o: not (
            o.source == 'mobile'
            and o.config_id.l10n_be_blackbox_be_id
            and not o.config_id.l10n_be_training_mode
            and not o.l10n_be_short_signature
        ))
        if orders:
            super(PosOrder, orders)._send_self_order_receipt()

    def _load_pos_self_data_fields(self, config):
        result = super()._load_pos_self_data_fields(config)
        return result + ['l10n_be_short_signature', 'l10n_be_event_label', 'l10n_be_event_counter', 'l10n_be_total_counter',
                         'l10n_be_fdm_id', 'l10n_be_fdm_date_time', 'l10n_be_pos_id', 'l10n_be_terminal_id', 'l10n_be_device_id',
                         'l10n_be_verification_url', 'l10n_be_pos_date_time', 'l10n_be_vat_calc', 'l10n_be_footer']
